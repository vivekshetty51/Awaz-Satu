"""
Voice Data Schemas for Awaaz Setu.

Architectural Context:
- Strict Pydantic V2 models for zero-cost runtime payload validation.
- Validates inbound telephony/WebRTC audio packets (base64 encoded audio) and
  serializes outbound multi-modal responses (transcription, LLM answer, synthesized audio).
- Ensures non-blocking parsing with lightweight, highly-optimized validators.
"""

import base64
import re
from typing import Literal
from pydantic import BaseModel, ConfigDict, Field, field_validator


class IncomingAudioPayload(BaseModel):
    """
    Inbound request schema representing audio stream frames or audio payloads
    received from telephony gateways (e.g., Asterisk/FreeSWITCH) or client devices.
    """

    user_phone: str = Field(
        ...,
        min_length=3,
        max_length=20,
        description="Caller's phone number or telephony identifier in standard or E.164 format.",
        examples=["+919876543210", "9876543210"],
    )
    audio_base64: str = Field(
        ...,
        min_length=1,
        description="Standard Base64-encoded audio payload (PCM/WAV/MP3).",
    )
    language: str = Field(
        default="hi",
        min_length=2,
        max_length=10,
        description="Target spoken language code (e.g., 'hi' for Hindi, 'bn', 'ta', 'te', 'en').",
        examples=["hi", "en", "mr"],
    )
    sample_rate: int = Field(
        default=8000,
        ge=4000,
        le=96000,
        description="Audio sampling rate in Hertz (e.g., 8000 Hz for narrowband PSTN/GSM, 16000 Hz for wideband).",
        examples=[8000, 16000, 44100, 48000],
    )

    model_config = ConfigDict(
        str_strip_whitespace=True,
        populate_by_name=True,
        json_schema_extra={
            "example": {
                "user_phone": "+919876543210",
                "audio_base64": "UklGRiQAAABXQVZFZm10IBAAAAABAAEAQB8AAEAfAAABAAgAZGF0YQAAAAA=",
                "language": "hi",
                "sample_rate": 8000,
            }
        },
    )

    @field_validator("user_phone")
    @classmethod
    def validate_user_phone(cls, value: str) -> str:
        """
        Validates that the telephone number is non-empty and conforms to standard phone characters.
        Allows leading '+' for international codes, digits, and optional hyphen/space separators.
        """
        cleaned = re.sub(r"[\s\-()]", "", value)
        if not cleaned:
            raise ValueError("user_phone cannot be empty or whitespace only.")

        # E.164 and standard telephony pattern: optional '+', followed by 3-15 digits
        if not re.match(r"^\+?[0-9]{3,15}$", cleaned):
            raise ValueError(
                f"Invalid phone number format '{value}'. Must be 3-15 digits, optionally prefixed with '+'."
            )
        return cleaned

    @field_validator("audio_base64")
    @classmethod
    def validate_audio_base64(cls, value: str) -> str:
        """
        Validates that the provided audio string is a well-formed Base64 representation.
        Checks for proper alphabet, padding, and decodability without keeping full binary in memory.
        """
        stripped = value.strip()
        if not stripped:
            raise ValueError("audio_base64 cannot be empty.")

        # Quick structural regex check for valid base64 characters & padding
        if not re.match(r"^[A-Za-z0-9+/]+={0,2}$", stripped):
            raise ValueError("audio_base64 string contains invalid Base64 characters.")

        try:
            # Validate decode capability safely
            # Using validate=True checks strict base64 padding
            base64.b64decode(stripped, validate=True)
        except Exception as exc:
            raise ValueError(f"audio_base64 is not valid Base64 encoded data: {exc}") from exc

        return stripped

    @field_validator("language")
    @classmethod
    def normalize_language(cls, value: str) -> str:
        """Normalizes language code to lower case."""
        return value.strip().lower()


class VoiceResponsePayload(BaseModel):
    """
    Outbound response schema representing the complete turn response
    for the voice pipeline (STT -> Reasoning Engine -> TTS).
    """

    status: Literal["success", "error"] = Field(
        ...,
        description="Overall execution status of the pipeline turn ('success' or 'error').",
        examples=["success", "error"],
    )
    recognized_text: str = Field(
        default="",
        description="Transcribed user speech generated by Speech-to-Text (STT).",
        examples=["नमस्ते, मुझे पीएम किसान योजना के बारे में जानकारी चाहिए।"],
    )
    ai_text_response: str = Field(
        default="",
        description="Textual response generated by the conversational AI / LLM pipeline.",
        examples=["पीएम किसान योजना के तहत पात्र किसानों को सालाना 6000 रुपये दिए जाते हैं।"],
    )
    output_audio_base64: str = Field(
        default="",
        description="Base64-encoded synthesized audio payload generated by Text-to-Speech (TTS).",
    )
    processing_time_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="End-to-end processing latency in milliseconds for telemetry and SLA tracking.",
        examples=[412.5],
    )
    provider_used: str = Field(
        ...,
        min_length=1,
        description="Open-source engine or local provider identifier used for synthesis and inference.",
        examples=["whisper-onnx + llama-cpp + piper-tts", "bhashini-open-pipeline", "offline-mock"],
    )

    model_config = ConfigDict(
        str_strip_whitespace=True,
        populate_by_name=True,
        json_schema_extra={
            "example": {
                "status": "success",
                "recognized_text": "नमस्ते",
                "ai_text_response": "नमस्ते! मैं आपकी किस प्रकार सहायता कर सकता हूँ?",
                "output_audio_base64": "UklGRiQAAABXQVZFZm10IBAAAAABAAEAQB8AAEAfAAABAAgAZGF0YQAAAAA=",
                "processing_time_ms": 320.4,
                "provider_used": "piper-tts-indic-onnx",
            }
        },
    )
